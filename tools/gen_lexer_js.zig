// writes src/lexer/tables.ts, the names the lexer's TypeScript reads the wasm output by

const std = @import("std");
const grammar = @import("grammar");

const Writer = std.Io.Writer;

pub fn main(init: std.process.Init) !void {
    var buf: [16 * 1024]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buf);
    try generate(&stdout.interface);
    try stdout.interface.flush();
}

fn generate(w: *Writer) Writer.Error!void {
    try w.writeAll("// generated by tools/gen_lexer_js.zig, do not edit\n");
    try writeEnum(w, "TAGS", grammar.syntax.Tag, null);
    try writeEnum(w, "MESSAGES", grammar.syntax.Message, grammar.syntax.Message.text);
}

fn writeEnum(
    w: *Writer,
    name: []const u8,
    comptime E: type,
    comptime text: ?fn (E) []const u8,
) !void {
    try w.print("export const {s}: readonly string[] = Object.freeze([\n", .{name});
    inline for (comptime std.enums.values(E)) |value| {
        const label = if (text) |f| f(value) else @tagName(value);
        try w.print("  \"{f}\",\n", .{std.zig.fmtString(label)});
    }
    try w.writeAll("]);\n");
}
