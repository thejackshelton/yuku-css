// writes src/decode.js, the decoder of the transfer format, from the Zig layouts

const std = @import("std");
const css = @import("yuku-css");
const ast = css.ast;
const rt = css.transfer;

const Writer = std.Io.Writer;
const node_data = @typeInfo(ast.NodeData).@"union";

pub fn main(init: std.process.Init) !void {
    var buf: [64 * 1024]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buf);
    try generate(&stdout.interface);
    try stdout.interface.flush();
}

// css-tree's types that pascal casing gets wrong
fn typeName(comptime name: []const u8) []const u8 {
    if (comptime std.mem.eql(u8, name, "cdo")) return "CDO";
    if (comptime std.mem.eql(u8, name, "cdc")) return "CDC";
    return snakeConvert(name, true);
}

// the fields css-tree leaves null
fn isNullable(comptime tag: []const u8, comptime field: []const u8) bool {
    const nullable = [_][2][]const u8{
        .{ "attribute_selector", "flags" },
        .{ "pseudo_class_selector", "children" },
        .{ "pseudo_element_selector", "children" },
        .{ "an_plus_b", "a" },
        .{ "an_plus_b", "b" },
    };
    inline for (nullable) |entry| {
        if (comptime std.mem.eql(u8, entry[0], tag) and std.mem.eql(u8, entry[1], field)) return true;
    }
    return false;
}

fn generate(w: *Writer) Writer.Error!void {
    try w.writeAll(
        \\// generated by tools/gen_decoder.zig, do not edit
        \\const NULL = -1;
        \\const _td = new TextDecoder();
        \\
    );
    try writeTables(w);
    try writeUtf16(w);
    try writeLines(w);
    try writeDecode(w);
    try writeDecodeTokens(w);
    try w.writeAll("export { decode, decodeTokens, tokenNames, tokenTypes };\n");
}

fn writeTables(w: *Writer) !void {
    try w.writeAll("const MATCHERS = [");
    for (ast.Matcher.strings, 0..) |matcher, i| {
        if (i > 0) try w.writeAll(", ");
        if (matcher) |text| try w.print("\"{s}\"", .{text}) else try w.writeAll("null");
    }
    try w.writeAll("];\nconst MESSAGES = [\n");
    inline for (comptime std.enums.values(ast.Message)) |message| {
        try w.print("  \"{f}\",\n", .{std.zig.fmtString(message.text())});
    }
    try w.writeAll("];\nconst tokenTypes = Object.freeze({\n");
    inline for (comptime std.enums.values(css.token.Tag)) |tag| {
        try w.print("  {s}: {d},\n", .{ comptime tag.typeName(), @backingInt(tag) });
    }
    try w.writeAll("});\nconst tokenNames = Object.freeze([\n");
    inline for (comptime std.enums.values(css.token.Tag)) |tag| {
        try w.print("  \"{s}\",\n", .{tag.name()});
    }
    try w.writeAll("]);\n");
}

// byte offsets to UTF-16 offsets, by the breakpoints at `base`; offsets come near in order, so the
// last breakpoint found is tried first
fn writeUtf16(w: *Writer) !void {
    try w.writeAll(
        \\function utf16(u32, base, count, firstNa) {
        \\  let j = 0;
        \\  return (v) => {
        \\    if (v <= firstNa) return v;
        \\    if ((j > 0 && u32[base + 2 * j - 2] > v) || (j < count && u32[base + 2 * j] <= v)) {
        \\      let lo = 0, hi = count;
        \\      while (lo < hi) {
        \\        const mid = (lo + hi) >>> 1;
        \\        if (u32[base + 2 * mid] <= v) lo = mid + 1;
        \\        else hi = mid;
        \\      }
        \\      j = lo;
        \\    }
        \\    return j === 0 ? v : v - u32[base + 2 * j - 1];
        \\  };
        \\}
        \\
    );
}

// css-tree's OffsetToLocation, from the line starts Zig writes: lines and columns count from
// `line` and `column`, a line after the first from column 1, and a byte order mark has neither
fn writeLines(w: *Writer) !void {
    try w.writeAll(
        \\function lines(src, starts, line, column, base) {
        \\  const count = starts.length;
        \\  const first = src.charCodeAt(0) === 0xFEFF || src.charCodeAt(0) === 0xFFFE ? 1 : 0;
        \\  let j = 0;
        \\  return (offset) => {
        \\    if (offset < first) return { offset: base + offset, line: 0, column: 0 };
        \\    if ((j > 0 && starts[j - 1] > offset) || (j < count && starts[j] <= offset)) {
        \\      let lo = 0, hi = count;
        \\      while (lo < hi) {
        \\        const mid = (lo + hi) >>> 1;
        \\        if (starts[mid] <= offset) lo = mid + 1;
        \\        else hi = mid;
        \\      }
        \\      j = lo;
        \\    }
        \\    return j === 0
        \\      ? { offset: base + offset, line, column: column + offset - first }
        \\      : { offset: base + offset, line: line + j, column: offset - starts[j - 1] + 1 };
        \\  };
        \\}
        \\
    );
}

fn writeDecode(w: *Writer) !void {
    try w.print(
        \\function decode(buffer, at, source, options) {{
        \\  const _u8 = new Uint8Array(buffer, at);
        \\  const _u32 = new Int32Array(buffer, at);
        \\  const _src = source;
        \\  const _srcLen = _u32[{[src]d}];
        \\  const _firstNa = _u32[{[fna]d}];
        \\  const nodeCount = _u32[{[nc]d}], extraCount = _u32[{[ec]d}], spLen = _u32[{[sp]d}];
        \\  const diagCount = _u32[{[dc]d}], root = _u32[{[root]d}];
        \\  const _extraBase = ({[hdr]d} + nodeCount * {[size]d}) >> 2;
        \\  const _spOff = (_extraBase + extraCount) * 4;
        \\  const _dBase = (_spOff + ((spLen + 3) & ~3)) >> 2;
        \\  const _p = utf16(_u32, _dBase + diagCount * {[dstride]d}, _u32[{[u16]d}], _firstNa);
        \\  const str = (s, e) => {{
        \\    if (s === e) return "";
        \\    if (s >= _srcLen) return _td.decode(_u8.subarray(_spOff + s - _srcLen, _spOff + e - _srcLen));
        \\    if (e <= _firstNa) return _src.slice(s, e);
        \\    return _src.slice(_p(s), _p(e));
        \\  }};
        \\  const important = (s, e) => {{
        \\    if (s === NULL) return false;
        \\    const word = str(s, e);
        \\    return word === "important" ? true : word;
        \\  }};
        \\  function nodeArr(s, len, depth) {{
        \\    const r = new Array(len);
        \\    const base = _extraBase + s;
        \\    for (let j = 0; j < len; j++) r[j] = node(_u32[base + j], depth);
        \\    return r;
        \\  }}
        \\  const positions = options.positions === true;
        \\  let point, file;
        \\  if (positions) {{
        \\    const lineBase = _dBase + diagCount * {[dstride]d} + _u32[{[u16]d}] * 2;
        \\    const starts = new Array(_u32[{[lc]d}]);
        \\    for (let j = 0; j < starts.length; j++) starts[j] = _p(_u32[lineBase + j]);
        \\    point = lines(_src, starts, options.line ?? 1, options.column ?? 1, options.offset ?? 0);
        \\    file = options.filename || "<unknown>";
        \\  }}
        \\  const loc = (s, e) => ({{ source: file, start: point(s), end: point(e) }});
        \\
    , .{
        .src = rt.HDR_SOURCE_LEN_U32,
        .fna = rt.HDR_FIRST_NON_ASCII_U32,
        .nc = rt.HDR_NODE_COUNT_U32,
        .ec = rt.HDR_EXTRA_COUNT_U32,
        .sp = rt.HDR_STRING_POOL_LEN_U32,
        .dc = rt.HDR_DIAGNOSTIC_COUNT_U32,
        .root = rt.HDR_ROOT_U32,
        .hdr = rt.HEADER_SIZE,
        .size = rt.NODE_SIZE,
        .dstride = rt.DIAGNOSTIC_SIZE / 4,
        .u16 = rt.HDR_UTF16_COUNT_U32,
        .lc = rt.HDR_LINE_COUNT_U32,
    });
    try writeNodeFunction(w, .offsets);
    try writeNodeFunction(w, .location);
    // children precede their parent, so index order builds past DEPTH_MAX without recursion
    try w.print(
        \\  const _inner = positions ? _location : _offsets;
        \\  const DEPTH_MAX = 128, _n = [];
        \\  function _deep(i) {{
        \\    while (_n.length <= i) _n.push(_inner(_n.length, DEPTH_MAX - 1));
        \\    return _n[i];
        \\  }}
        \\  const node = _inner;
        \\  const diagnostics = new Array(diagCount);
        \\  for (let j = 0; j < diagCount; j++) {{
        \\    const d = _dBase + j * {[stride]d};
        \\    diagnostics[j] = {{ message: MESSAGES[_u32[d + {[m]d}]], start: _p(_u32[d + {[s]d}]), end: _p(_u32[d + {[e]d}]) }};
        \\  }}
        \\  return {{ stylesheet: node(root, 0), diagnostics }};
        \\}}
        \\
    , .{
        .stride = rt.DIAGNOSTIC_SIZE / 4,
        .m = rt.DIAGNOSTIC_MESSAGE_U32,
        .s = rt.DIAGNOSTIC_START_U32,
        .e = rt.DIAGNOSTIC_END_U32,
    });
}

const Mode = enum { offsets, location };

fn writeNodeFunction(w: *Writer, comptime mode: Mode) !void {
    comptime std.debug.assert(rt.NODE_FLAGS_OFFSET == 2);
    try w.print(
        \\  function _{[name]s}(i, depth) {{
        \\    if (depth >= DEPTH_MAX) return _deep(i);
        \\    const b = (i * {[size]d} + {[hdr]d}) >> 2;
        \\    const h0 = _u32[b];
        \\    const flags = h0 >>> 16;
        \\    let start = _u32[b + {[ss]d}], end = _u32[b + {[se]d}];
        \\    if (end > _firstNa) {{ start = _p(start); end = _p(end); }}
        \\    switch (h0 & 255) {{
        \\
    , .{
        .name = @tagName(mode),
        .size = rt.NODE_SIZE,
        .hdr = rt.HEADER_SIZE,
        .ss = rt.NODE_SPAN_START_U32,
        .se = rt.NODE_SPAN_END_U32,
    });
    inline for (node_data.field_names, node_data.field_types, 0..) |name, Payload, tag| {
        try writeCase(w, mode, tag, name, Payload);
    }
    try w.writeAll(
        \\    }
        \\  }
        \\
    );
}

fn writeCase(w: *Writer, comptime mode: Mode, comptime tag: usize, comptime name: []const u8, comptime T: type) !void {
    @setEvalBranchQuota(100_000);
    const info = @typeInfo(T).@"struct";
    try w.print("    case {d}: {{", .{tag});
    const slots = comptime rt.totalU32Slots(T);
    if (slots > 0) {
        try w.writeAll(" const ");
        inline for (0..slots) |k| {
            if (k > 0) try w.writeAll(", ");
            try w.print("f{d} = _u32[b + {d}]", .{ k + 1, k + rt.NODE_HEADER_U32S });
        }
        try w.writeAll(";");
    }
    try w.print(" return {{ type: \"{s}\", ", .{comptime typeName(name)});
    switch (mode) {
        .offsets => try w.writeAll("start, end"),
        // css-tree gives the descendant combinator, whose name is no slice of the source, no position
        .location => if (comptime std.mem.eql(u8, name, "combinator"))
            try w.writeAll("loc: f1 >= _srcLen ? null : loc(start, end)")
        else
            try w.writeAll("loc: loc(start, end)"),
    }
    inline for (info.field_names, info.field_types, 0..) |field, Field, i| {
        try w.print(", {s}: ", .{comptime snakeConvert(field, false)});
        const s = comptime rt.u32SlotForField(T, i) + 1;
        const nullable = comptime isNullable(name, field);
        if (Field == ast.NodeIndex) {
            try w.print("f{d} === NULL ? null : node(f{d}, depth + 1)", .{ s, s });
        } else if (Field == ast.IndexRange) {
            if (nullable) try w.print("f{d} === NULL ? null : ", .{s});
            try w.print("nodeArr(f{d}, f{d}, depth + 1)", .{ s, s + 1 });
        } else if (Field == ast.String) {
            if (comptime std.mem.eql(u8, name, "declaration") and std.mem.eql(u8, field, "important")) {
                try w.print("important(f{d}, f{d})", .{ s, s + 1 });
            } else if (comptime std.mem.eql(u8, name, "combinator")) {
                // only the descendant combinator's name is no slice of the source
                try w.print("f{d} >= _srcLen ? \" \" : str(f{d}, f{d})", .{ s, s, s + 1 });
            } else {
                if (nullable) try w.print("f{d} === NULL ? null : ", .{s});
                try w.print("str(f{d}, f{d})", .{ s, s + 1 });
            }
        } else if (Field == ast.Matcher) {
            const bit = comptime rt.flagBitForField(T, i);
            const mask = comptime (1 << rt.enumBitWidth(Field)) - 1;
            try w.print("MATCHERS[(flags >> {d}) & {d}]", .{ bit, mask });
        } else {
            @compileError("no decoder for " ++ @typeName(Field));
        }
    }
    try w.writeAll(" }; }\n");
}

fn writeDecodeTokens(w: *Writer) !void {
    try w.print(
        \\function decodeTokens(buffer, at, source) {{
        \\  const _u32 = new Uint32Array(buffer, at);
        \\  const count = _u32[{[count]d}], firstNa = _u32[{[fna]d}];
        \\  const p = utf16(_u32, {[hdr]d} + count * {[stride]d}, _u32[{[u16]d}], firstNa);
        \\  const out = new Uint32Array(count);
        \\  for (let i = 0, b = {[hdr]d}; i < count; i++, b += {[stride]d}) {{
        \\    out[i] = ((_u32[b + {[tag]d}] & 255) << 24) | p(_u32[b + {[end]d}]);
        \\  }}
        \\  return out;
        \\}}
        \\
    , .{
        .count = rt.TOKENS_COUNT_U32,
        .fna = rt.TOKENS_FIRST_NON_ASCII_U32,
        .u16 = rt.TOKENS_UTF16_COUNT_U32,
        .hdr = rt.TOKENS_HEADER_SIZE / 4,
        .stride = rt.TOKEN_SIZE / 4,
        .end = rt.TOKEN_END_U32,
        .tag = rt.TOKEN_TAG_U32,
    });
}

fn snakeConvert(comptime name: []const u8, comptime pascal: bool) []const u8 {
    comptime {
        var out: []const u8 = "";
        var upper = pascal;
        for (name) |c| {
            if (c == '_') {
                upper = true;
            } else {
                out = out ++ &[_]u8{if (upper) std.ascii.toUpper(c) else c};
                upper = false;
            }
        }
        return out;
    }
}
