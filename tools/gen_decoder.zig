// writes src/decode.js, the decoder of the transfer format, from the Zig layouts

const std = @import("std");
const css = @import("yuku-css");
const ast = css.ast;
const rt = css.transfer;

const Writer = std.Io.Writer;
const node_data = @typeInfo(ast.NodeData).@"union";

pub fn main(init: std.process.Init) !void {
    var buf: [64 * 1024]u8 = undefined;
    var stdout = std.Io.File.stdout().writer(init.io, &buf);
    try generate(&stdout.interface);
    try stdout.interface.flush();
}

// the enums of node fields, each decoded through a table of its `strings`
const enums = .{ ast.Matcher, ast.MediaModifier, ast.ConditionKind, ast.Comparison };

fn enumTable(comptime E: type) []const u8 {
    comptime {
        const name = @typeName(E);
        const short = name[(std.mem.findScalarLast(u8, name, '.') orelse return name) + 1 ..];
        var out: []const u8 = "";
        for (short, 0..) |c, i| {
            if (i > 0 and std.ascii.isUpper(c)) out = out ++ "_";
            out = out ++ &[_]u8{std.ascii.toUpper(c)};
        }
        return out;
    }
}

// css-tree's types that pascal casing gets wrong
fn typeName(comptime name: []const u8) []const u8 {
    if (comptime std.mem.eql(u8, name, "cdo")) return "CDO";
    if (comptime std.mem.eql(u8, name, "cdc")) return "CDC";
    return snakeConvert(name, true);
}

// the fields css-tree leaves null
fn isNullable(comptime tag: []const u8, comptime field: []const u8) bool {
    const nullable = [_][2][]const u8{
        .{ "attribute_selector", "flags" },
        .{ "pseudo_class_selector", "children" },
        .{ "pseudo_element_selector", "children" },
        .{ "an_plus_b", "a" },
        .{ "an_plus_b", "b" },
        .{ "media_query", "media_type" },
        .{ "general_enclosed", "function" },
    };
    inline for (nullable) |entry| {
        if (comptime std.mem.eql(u8, entry[0], tag) and std.mem.eql(u8, entry[1], field)) return true;
    }
    return false;
}

fn generate(w: *Writer) Writer.Error!void {
    try w.writeAll(
        \\// generated by tools/gen_decoder.zig, do not edit
        \\const NULL = -1;
        \\const _td = new TextDecoder();
        \\
    );
    try writeTables(w);
    try writeUtf16(w);
    try writeLines(w);
    try writeDecode(w);
    try writeDecodeTokens(w);
    try w.writeAll("export { atrules, decode, decodeTokens, tokenNames, tokenTypes };\n");
}

fn writeTables(w: *Writer) !void {
    inline for (enums) |E| {
        try w.print("const {s} = [", .{comptime enumTable(E)});
        for (E.strings, 0..) |text, i| {
            if (i > 0) try w.writeAll(", ");
            if (text) |t| try w.print("\"{s}\"", .{t}) else try w.writeAll("null");
        }
        try w.writeAll("];\n");
    }
    try w.writeAll("const atrules = Object.freeze({\n");
    inline for (comptime std.enums.values(css.parser.Atrule)) |name| {
        if (name == .unknown) continue;
        try w.print("  \"{s}\": {d},\n", .{ comptime name.text(), @backingInt(name) });
    }
    try w.writeAll("});\nconst MESSAGES = [\n");
    inline for (comptime std.enums.values(ast.Message)) |message| {
        try w.print("  \"{f}\",\n", .{std.zig.fmtString(message.text())});
    }
    try w.writeAll("];\nconst tokenTypes = Object.freeze({\n");
    inline for (comptime std.enums.values(css.token.Tag)) |tag| {
        try w.print("  {s}: {d},\n", .{ comptime tag.typeName(), @backingInt(tag) });
    }
    try w.writeAll("});\nconst tokenNames = Object.freeze([\n");
    inline for (comptime std.enums.values(css.token.Tag)) |tag| {
        try w.print("  \"{s}\",\n", .{tag.name()});
    }
    try w.writeAll("]);\n");
}

// byte offsets to UTF-16 offsets, by the breakpoints at `base`; offsets come near in order, so the
// last breakpoint found is tried first
fn writeUtf16(w: *Writer) !void {
    try w.writeAll(
        \\function utf16(u32, base, count, firstNa) {
        \\  let j = 0;
        \\  return (v) => {
        \\    if (v <= firstNa) return v;
        \\    if ((j > 0 && u32[base + 2 * j - 2] > v) || (j < count && u32[base + 2 * j] <= v)) {
        \\      let lo = 0, hi = count;
        \\      while (lo < hi) {
        \\        const mid = (lo + hi) >>> 1;
        \\        if (u32[base + 2 * mid] <= v) lo = mid + 1;
        \\        else hi = mid;
        \\      }
        \\      j = lo;
        \\    }
        \\    return j === 0 ? v : v - u32[base + 2 * j - 1];
        \\  };
        \\}
        \\
    );
}

// css-tree's OffsetToLocation, with lines and columns counted from `line` and `column`, a line after
// the first from column 1, and none for a byte order mark. The parser records where lines start as
// it lexes, and an offset's line is found from the first line past the start of its 64-unit block
fn writeLines(w: *Writer) !void {
    try w.writeAll(
        \\// S[j] is where line j starts, the first placed so that its columns count from `column`
        \\function locator(src, starts, line, column, base, file) {
        \\  const count = starts.length;
        \\  const first = src.charCodeAt(0) === 0xFEFF || src.charCodeAt(0) === 0xFFFE ? 1 : 0;
        \\  const S = new Int32Array(count + 2);
        \\  S[0] = first - column + 1;
        \\  S.set(starts, 1);
        \\  S[count + 1] = 0x7fffffff;
        \\  const blocks = new Int32Array((src.length >> 6) + 2);
        \\  for (let b = 0, j = 0; b < blocks.length; b++) {
        \\    while (S[j + 1] <= b << 6) j++;
        \\    blocks[b] = j;
        \\  }
        \\  const point = (offset, j) =>
        \\    offset < first
        \\      ? { offset: base + offset, line: 0, column: 0 }
        \\      : { offset: base + offset, line: line + j, column: offset - S[j] + 1 };
        \\  if (first === 1) {
        \\    return (s, e) => {
        \\      let j = blocks[s >> 6];
        \\      while (S[j + 1] <= s) j++;
        \\      const start = point(s, j);
        \\      if (S[j + 1] <= e) {
        \\        j = blocks[e >> 6];
        \\        while (S[j + 1] <= e) j++;
        \\      }
        \\      return { source: file, start, end: point(e, j) };
        \\    };
        \\  }
        \\  // the tree asks in the order of its starts, so the last start's line is tried first
        \\  let last = 0;
        \\  return (s, e) => {
        \\    let j = last;
        \\    if (S[j + 1] <= s || S[j] > s) {
        \\      j = blocks[s >> 6];
        \\      while (S[j + 1] <= s) j++;
        \\      last = j;
        \\    }
        \\    const startLine = line + j, startColumn = s - S[j] + 1;
        \\    if (S[j + 1] <= e) {
        \\      j = blocks[e >> 6];
        \\      while (S[j + 1] <= e) j++;
        \\    }
        \\    // one literal, so that the three objects are allocated together
        \\    return {
        \\      source: file,
        \\      start: { offset: base + s, line: startLine, column: startColumn },
        \\      end: { offset: base + e, line: line + j, column: e - S[j] + 1 },
        \\    };
        \\  };
        \\}
        \\
    );
}

fn writeDecode(w: *Writer) !void {
    // the node functions are closures over one buffer, which V8 runs faster than functions over
    // module state, whose allocation sites keep deoptimizing them
    try w.print(
        \\// the tree from the buffer at `at`, with `loc` from `locator` or null for offsets
        \\function tree(buffer, at, source, loc) {{
        \\  const _u8 = new Uint8Array(buffer, at);
        \\  const _u32 = new Int32Array(buffer, at);
        \\  const _src = source;
        \\  const _srcLen = _u32[{[src]d}];
        \\  const _extraBase = ({[hdr]d} + _u32[{[nc]d}] * {[size]d}) >> 2;
        \\  const _spOff = (_extraBase + _u32[{[ec]d}]) * 4;
        \\  // node strings in the source come as UTF-16 offsets, the pool's as bytes past the source's
        \\  const str = (s, e) => {{
        \\    if (s === e) return "";
        \\    if (s >= _srcLen) return _td.decode(_u8.subarray(_spOff + s - _srcLen, _spOff + e - _srcLen));
        \\    return _src.slice(s, e);
        \\  }};
        \\  const important = (s, e) => {{
        \\    if (s === NULL) return false;
        \\    const word = str(s, e);
        \\    return word === "important" ? true : word;
        \\  }};
        \\  const DEPTH_MAX = 128, _n = [];
        \\  // children precede their parent, so index order builds past DEPTH_MAX without recursion
        \\  function _deep(i, inner) {{
        \\    while (_n.length <= i) _n.push(inner(_n.length, DEPTH_MAX - 1));
        \\    return _n[i];
        \\  }}
        \\
    , .{
        .src = rt.HDR_SOURCE_LEN_U32,
        .hdr = rt.HEADER_SIZE,
        .nc = rt.HDR_NODE_COUNT_U32,
        .size = rt.NODE_SIZE,
        .ec = rt.HDR_EXTRA_COUNT_U32,
    });
    try writeNodeFunction(w, .offsets);
    try writeNodeFunction(w, .location);
    try w.print(
        \\  return loc === null ? _offsets(_u32[{[root]d}], 0) : _location(_u32[{[root]d}], 0);
        \\}}
        \\
    , .{ .root = rt.HDR_ROOT_U32 });
    try w.print(
        \\// everything but the tree, which `open` builds when `ast` is first read
        \\function decode(buffer, at, source, options, withTokens, open) {{
        \\  const u32 = new Int32Array(buffer, at);
        \\  const srcLen = u32[{[src]d}], firstNa = u32[{[fna]d}];
        \\  const nodeCount = u32[{[nc]d}], extraCount = u32[{[ec]d}], spLen = u32[{[sp]d}];
        \\  const diagCount = u32[{[dc]d}];
        \\  const extraBase = ({[hdr]d} + nodeCount * {[size]d}) >> 2;
        \\  const spOff = (extraBase + extraCount) * 4;
        \\  const dBase = (spOff + ((spLen + 3) & ~3)) >> 2;
        \\  const p = utf16(u32, dBase + diagCount * {[dstride]d}, u32[{[u16]d}], firstNa);
        \\  const positions = options.positions === true;
        \\  const commentBase = dBase + diagCount * {[dstride]d} + u32[{[u16]d}] * 2;
        \\  const commentCount = u32[{[cc]d}];
        \\  const lineBase = commentBase + commentCount * 2, lineCount = u32[{[lc]d}];
        \\  const tokenBase = lineBase + lineCount, tokenCount = u32[{[tc]d}];
        \\  let loc = null;
        \\  if (positions) {{
        \\    // the line starts in UTF-16 units, copied as they are where the source is ASCII
        \\    let starts = new Int32Array(buffer, at + lineBase * 4, lineCount);
        \\    if (lineCount > 0 && starts[lineCount - 1] > firstNa) starts = starts.map(p);
        \\    const line = options.line ?? 1, column = options.column ?? 1;
        \\    loc = locator(source, starts, line, column, options.offset ?? 0, options.filename || "<unknown>");
        \\  }}
        \\  const path = options.filename ?? null;
        \\  const diagnostics = new Array(diagCount);
        \\  const u8 = new Uint8Array(buffer, at);
        \\  const str = (s, e) => (s >= srcLen ? _td.decode(u8.subarray(spOff + s - srcLen, spOff + e - srcLen)) : source.slice(s, e));
        \\  for (let j = 0; j < diagCount; j++) {{
        \\    const d = dBase + j * {[dstride]d};
        \\    const a = u32[d + {[a]d}], text = MESSAGES[u32[d + {[m]d}]];
        \\    const b = u32[d + {[a]d} + 1];
        \\    // diagnostic offsets are bytes, so a source argument is mapped as they are
        \\    const argument = a === NULL ? "" : a >= srcLen ? str(a, b) : str(p(a), p(b));
        \\    const message = a === NULL ? text : text.replace("{{}}", argument);
        \\    const start = p(u32[d + {[s]d}]), end = p(u32[d + {[e]d}]);
        \\    diagnostics[j] = {{ severity: "error", message, path, start, end, labels: [], help: null }};
        \\  }}
        \\  const spans = commentCount === 0 ? null : new Int32Array(commentCount * 2);
        \\  for (let j = 0; j < commentCount * 2; j++) spans[j] = p(u32[commentBase + j]);
        \\  let tokens;
        \\  if (withTokens) {{
        \\    tokens = new Uint32Array(tokenCount);
        \\    for (let j = 0, b = tokenBase; j < tokenCount; j++, b += {[tstride]d}) {{
        \\      tokens[j] = ((u32[b + {[ttag]d}] & 255) << 24) | p(u32[b + {[tend]d}]);
        \\    }}
        \\  }}
        \\  let comments;
        \\  const result = {{
        \\    ast: undefined,
        \\    get comments() {{
        \\      if (comments !== undefined) return comments;
        \\      comments = new Array(commentCount);
        \\      for (let j = 0; j < commentCount; j++) {{
        \\        const s = spans[2 * j], e = spans[2 * j + 1];
        \\        const value = source.startsWith("*/", e - 2) ? source.slice(s + 2, e - 2) : source.slice(s + 2, e);
        \\        comments[j] = positions ? {{ type: "Comment", loc: loc(s, e), value }} : {{ type: "Comment", start: s, end: e, value }};
        \\      }}
        \\      return comments;
        \\    }},
        \\    tokens,
        \\    diagnostics,
        \\  }};
        \\  TREES.set(result, () => open((buffer, at) => tree(buffer, at, source, loc)));
        \\  return Object.defineProperty(result, "ast", AST);
        \\}}
        \\// each result's tree, built when `ast` is first read
        \\const TREES = new WeakMap();
        \\// one getter for every result, as V8 keeps pretenuring the tree's nodes and deoptimizing
        \\// the node functions when each result has its own
        \\const AST = {{
        \\  get() {{
        \\    const build = TREES.get(this);
        \\    return build === undefined ? undefined : own(this, build());
        \\  }},
        \\  set(value) {{
        \\    own(this, value);
        \\  }},
        \\  enumerable: true,
        \\  configurable: true,
        \\}};
        \\function own(result, ast) {{
        \\  TREES.delete(result);
        \\  Object.defineProperty(result, "ast", {{ value: ast, writable: true, enumerable: true, configurable: true }});
        \\  return ast;
        \\}}
        \\
    , .{
        .src = rt.HDR_SOURCE_LEN_U32,
        .fna = rt.HDR_FIRST_NON_ASCII_U32,
        .nc = rt.HDR_NODE_COUNT_U32,
        .ec = rt.HDR_EXTRA_COUNT_U32,
        .sp = rt.HDR_STRING_POOL_LEN_U32,
        .dc = rt.HDR_DIAGNOSTIC_COUNT_U32,
        .hdr = rt.HEADER_SIZE,
        .size = rt.NODE_SIZE,
        .dstride = rt.DIAGNOSTIC_SIZE / 4,
        .u16 = rt.HDR_UTF16_COUNT_U32,
        .cc = rt.HDR_COMMENT_COUNT_U32,
        .lc = rt.HDR_LINE_COUNT_U32,
        .tc = rt.HDR_TOKEN_COUNT_U32,
        .m = rt.DIAGNOSTIC_MESSAGE_U32,
        .s = rt.DIAGNOSTIC_START_U32,
        .e = rt.DIAGNOSTIC_END_U32,
        .a = rt.DIAGNOSTIC_ARGUMENT_U32,
        .tstride = rt.TOKEN_SIZE / 4,
        .ttag = rt.TOKEN_TAG_U32,
        .tend = rt.TOKEN_END_U32,
    });
}

const Mode = enum { offsets, location };

// each mode has its own list builder, so every call between node functions has one target
fn writeNodeFunction(w: *Writer, comptime mode: Mode) !void {
    comptime std.debug.assert(rt.NODE_FLAGS_OFFSET == 2);
    try w.print(
        \\  function _{[name]s}Arr(s, len, depth) {{
        \\    const base = _extraBase + s;
        \\
    , .{ .name = @tagName(mode) });
    // short lists are array literals, whose allocation sites V8 pretenures with the nodes, where
    // `new Array` lists stay young and are copied by every scavenge, but with positions the
    // literals measured slower once small sheets had run first, as V8 then kept their sites young
    if (mode == .offsets) try w.print(
        \\    switch (len) {{
        \\    case 0: return [];
        \\    case 1: return [_{[name]s}(_u32[base], depth)];
        \\    case 2: return [_{[name]s}(_u32[base], depth), _{[name]s}(_u32[base + 1], depth)];
        \\    case 3: return [_{[name]s}(_u32[base], depth), _{[name]s}(_u32[base + 1], depth), _{[name]s}(_u32[base + 2], depth)];
        \\    }}
        \\
    , .{ .name = @tagName(mode) });
    try w.print(
        \\    const r = new Array(len);
        \\    for (let j = 0; j < len; j++) r[j] = _{[name]s}(_u32[base + j], depth);
        \\    return r;
        \\  }}
        \\  function _{[name]s}(i, depth) {{
        \\    if (depth >= DEPTH_MAX) return _deep(i, _{[name]s});
        \\    const b = (i * {[size]d} + {[hdr]d}) >> 2;
        \\    const h0 = _u32[b];
        \\    const start = _u32[b + {[ss]d}], end = _u32[b + {[se]d}];
        \\    switch (h0 & 255) {{
        \\
    , .{
        .name = @tagName(mode),
        .size = rt.NODE_SIZE,
        .hdr = rt.HEADER_SIZE,
        .ss = rt.NODE_SPAN_START_U32,
        .se = rt.NODE_SPAN_END_U32,
    });
    inline for (node_data.field_names, node_data.field_types, 0..) |name, Payload, tag| {
        try writeCase(w, mode, tag, name, Payload);
    }
    try w.writeAll(
        \\    }
        \\  }
        \\
    );
}

fn writeCase(w: *Writer, comptime mode: Mode, comptime tag: usize, comptime name: []const u8, comptime T: type) !void {
    @setEvalBranchQuota(100_000);
    const info = @typeInfo(T).@"struct";
    const self = "_" ++ @tagName(mode);
    try w.print("    case {d}: {{", .{tag});
    const slots = comptime rt.totalU32Slots(T);
    if (slots > 0) {
        try w.writeAll(" const ");
        inline for (0..slots) |k| {
            if (k > 0) try w.writeAll(", ");
            try w.print("f{d} = _u32[b + {d}]", .{ k + 1, k + rt.NODE_HEADER_U32S });
        }
        try w.writeAll(";");
    }
    try w.print(" return {{ type: \"{s}\", ", .{comptime typeName(name)});
    switch (mode) {
        .offsets => try w.writeAll("start, end"),
        // css-tree gives the descendant combinator, whose name is no slice of the source, no position
        .location => if (comptime std.mem.eql(u8, name, "combinator"))
            try w.writeAll("loc: f1 >= _srcLen ? null : loc(start, end)")
        else if (comptime std.mem.eql(u8, name, "white_space"))
            try w.writeAll("loc: null")
        else
            try w.writeAll("loc: loc(start, end)"),
    }
    inline for (info.field_names, info.field_types, 0..) |field, Field, i| {
        try w.print(", {s}: ", .{comptime snakeConvert(field, false)});
        const s = comptime rt.u32SlotForField(T, i) + 1;
        const nullable = comptime isNullable(name, field);
        if (Field == ast.NodeIndex) {
            try w.print("f{d} === NULL ? null : {s}(f{d}, depth + 1)", .{ s, self, s });
        } else if (Field == ast.IndexRange) {
            if (nullable) try w.print("f{d} === NULL ? null : ", .{s});
            try w.print("{s}Arr(f{d}, f{d}, depth + 1)", .{ self, s, s + 1 });
        } else if (Field == ast.String) {
            if (comptime std.mem.eql(u8, name, "declaration") and std.mem.eql(u8, field, "important")) {
                try w.print("important(f{d}, f{d})", .{ s, s + 1 });
            } else if (comptime std.mem.eql(u8, name, "combinator")) {
                // only the descendant combinator's name is no slice of the source
                try w.print("f{d} >= _srcLen ? \" \" : str(f{d}, f{d})", .{ s, s, s + 1 });
            } else {
                if (nullable) try w.print("f{d} === NULL ? null : ", .{s});
                try w.print("str(f{d}, f{d})", .{ s, s + 1 });
            }
        } else if (@typeInfo(Field) == .@"enum" and @hasDecl(Field, "strings")) {
            const bit = comptime rt.flagBitForField(T, i) + 16;
            const mask = comptime (1 << rt.enumBitWidth(Field)) - 1;
            try w.print("{s}[(h0 >>> {d}) & {d}]", .{ comptime enumTable(Field), bit, mask });
        } else {
            @compileError("no decoder for " ++ @typeName(Field));
        }
    }
    try w.writeAll(" }; }\n");
}

fn writeDecodeTokens(w: *Writer) !void {
    try w.print(
        \\function decodeTokens(buffer, at, source) {{
        \\  const _u32 = new Uint32Array(buffer, at);
        \\  const count = _u32[{[count]d}], firstNa = _u32[{[fna]d}];
        \\  const p = utf16(_u32, {[hdr]d} + count * {[stride]d}, _u32[{[u16]d}], firstNa);
        \\  const out = new Uint32Array(count);
        \\  for (let i = 0, b = {[hdr]d}; i < count; i++, b += {[stride]d}) {{
        \\    out[i] = ((_u32[b + {[tag]d}] & 255) << 24) | p(_u32[b + {[end]d}]);
        \\  }}
        \\  return out;
        \\}}
        \\
    , .{
        .count = rt.TOKENS_COUNT_U32,
        .fna = rt.TOKENS_FIRST_NON_ASCII_U32,
        .u16 = rt.TOKENS_UTF16_COUNT_U32,
        .hdr = rt.TOKENS_HEADER_SIZE / 4,
        .stride = rt.TOKEN_SIZE / 4,
        .end = rt.TOKEN_END_U32,
        .tag = rt.TOKEN_TAG_U32,
    });
}

fn snakeConvert(comptime name: []const u8, comptime pascal: bool) []const u8 {
    comptime {
        var out: []const u8 = "";
        var upper = pascal;
        for (name) |c| {
            if (c == '_') {
                upper = true;
            } else {
                out = out ++ &[_]u8{if (upper) std.ascii.toUpper(c) else c};
                upper = false;
            }
        }
        return out;
    }
}
